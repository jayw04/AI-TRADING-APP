def cache_identity(root: Path, symbols: list[str], expected_session_date: str) -> dict:
    """Bind the BAR-CACHE identity separately from the factor-store identity.

    The two are different sources (Alpaca bars vs the Sharadar factor store) and must not be
    conflated in evidence. A rehearsal warms this cache, so a later run could silently size from
    rehearsal-era parquet unless freshness is asserted per symbol actually used.
    """
    import pandas as pd

    bucket = expected_session_date[:7]  # YYYY-MM — the open bucket
    per: dict[str, dict] = {}
    stale: list[str] = []
    for sym in symbols:
        f = root / sym.upper() / "1Day" / f"{bucket}.parquet"
        if not f.exists():
            per[sym] = {"bucket_file": str(f), "exists": False}
            stale.append(sym)
            continue
        st = f.stat()
        mtime = datetime.fromtimestamp(st.st_mtime, UTC)
        entry = {
            "bucket_file": str(f),
            "exists": True,
            "mtime_utc": mtime.isoformat(),
            "size_bytes": st.st_size,
        }
        try:
            df = pd.read_parquet(f)
            idx = df.index
            last = (
                str(max(idx)) if getattr(idx, "dtype", None) is not None
                and str(getattr(idx, "dtype", "")).startswith("datetime")
                else (str(df["t"].max()) if "t" in df.columns else None)
            )
            entry["rows"] = int(len(df))
            entry["max_bar"] = last
        except Exception as exc:  # noqa: BLE001 — record, never guess
            entry["read_error"] = str(exc)[:160]
        # Freshness: the open bucket must have been (re)written on the run's own session date.
        if mtime.date().isoformat() < expected_session_date:
            stale.append(sym)
        per[sym] = entry
    return {
        "root": str(root),
        "open_bucket": bucket,
        "expected_session_date": expected_session_date,
        "assessed_symbol_count": len(symbols),
        "symbols": per,
        "stale_or_missing_symbols": sorted(stale),
        "is_fresh": not stale,
    }


