async def cmd_execute(args) -> None:
    raise SystemExit(
        "EXECUTION DISABLED IN THE PLANNER: the v1.3 transition executes only via "
        "the staged executor with the frozen quote/drift gates and stage-status "
        "model (separate tool, separate owner authorization).")
    import urllib.error
    import urllib.request

    path = Path(args.manifest)
    m = json.loads(path.read_text())

    status = m.get("artifact_status", "")
    if "DRY_RUN" in status or "NOT_AUTHORIZED" in status or "SUPERSEDED" in status:
        raise SystemExit(f"ABORT: manifest is labeled {status!r} and cannot be executed.")

    stated = m.pop("manifest_sha256")
    recomputed = sha256_of(canonical(m))
    m["manifest_sha256"] = stated
    if stated != recomputed:
        raise SystemExit(f"ABORT: manifest hash mismatch\n  stated {stated}\n  actual {recomputed}")
    if args.approve_sha != stated:
        raise SystemExit(
            f"ABORT: --approve-sha does not match the manifest\n"
            f"  approved {args.approve_sha}\n  manifest {stated}"
        )
    print(f"manifest {stated[:16]}… verified, {len(m['orders'])} orders")

    # ---- safeguards: duplicate symbols / opposing orders ------------------------------
    seen: dict[str, str] = {}
    for o in m["orders"]:
        s = o["symbol"]
        if s in seen:
            raise SystemExit(f"ABORT: symbol {s} appears twice ({seen[s]} then {o['side']})")
        seen[s] = o["side"]

    # ---- re-read live state immediately before release --------------------------------
    from sqlalchemy import text

    from app.db.session import get_sessionmaker
    sf = get_sessionmaker()
    async with sf() as session:
        open_n = (await session.execute(text(
            "select count(*) from orders where account_id=:a and status not in "
            "('FILLED','CANCELLED','REJECTED','EXPIRED')"), {"a": ACCOUNT_ID})).scalar()
        pos = {r[0]: str(r[1]) for r in (await session.execute(text(
            "select s.ticker, p.qty from positions p join symbols s on s.id=p.symbol_id "
            "where p.account_id=:a"), {"a": ACCOUNT_ID})).all()}
    if open_n:
        raise SystemExit(f"ABORT: {open_n} open order(s) appeared since the manifest")

    manifest_pos = m["pre_run_state"]["positions"]
    drift = {
        s: (manifest_pos.get(s), pos.get(s))
        for s in set(manifest_pos) | set(pos)
        if str(manifest_pos.get(s)) != str(pos.get(s))
    }
    if drift and not args.accept_drift:
        print("ABORT: positions differ from the manifest:")
        for s, (was, now) in sorted(drift.items()):
            print(f"    {s}: manifest {was} -> live {now}")
        raise SystemExit("re-plan, or pass --accept-drift only with an explained cause")

    # ---- login -------------------------------------------------------------------------
    pw = os.environ.get("WB_PASSWORD")
    if not pw:
        raise SystemExit("ABORT: WB_PASSWORD not set")
    base = "http://localhost:8000/api/v1"

    def post(url, body, cookie=None):
        req = urllib.request.Request(
            url, data=json.dumps(body).encode(),
            headers={"Content-Type": "application/json", **({"Cookie": cookie} if cookie else {})},
            method="POST",
        )
        with urllib.request.urlopen(req, timeout=30) as r:
            return r.status, json.loads(r.read() or b"{}"), r.headers.get("set-cookie", "")

    st, _, setc = post(f"{base}/auth/login",
                       {"email": "combined-book@globalcomplyai.com", "password": pw})
    cookie = setc.split(";")[0]
    print(f"login {st}")

    short = stated[:8]
    submitted, refused = [], []
    for o in m["orders"]:
        coid = f"twb-otr-{short}-{o['seq']:03d}"
        body = {
            "symbol": o["symbol"], "side": o["side"], "qty": o["qty"],
            "type": "market", "tif": "day",
            "account_id": ACCOUNT_ID, "source": "strategy", "strategy_id": STRATEGY_ID,
            "client_order_id": coid,
        }
        if args.dry_run:
            print(f"  DRY  {o['seq']:3d} {o['side']:4s} {o['symbol']:6s} {o['qty']}  coid={coid}")
            continue
        try:
            st, resp, _ = post(f"{base}/orders", body, cookie)
            rej = resp.get("rejection_reason")
            if rej:
                refused.append((o, rej))
                print(f"  RISK REFUSAL on {o['symbol']}: {rej} — STOPPING")
                break
            submitted.append((o, resp.get("id")))
            print(f"  OK   {o['seq']:3d} {o['side']:4s} {o['symbol']:6s} {o['qty']} -> {resp.get('id')}")
        except urllib.error.HTTPError as e:
            detail = e.read().decode()[:300]
            refused.append((o, f"HTTP {e.code}: {detail}"))
            print(f"  HTTP {e.code} on {o['symbol']}: {detail} — STOPPING")
            break
        await asyncio.sleep(float(args.pacing))

    print(f"\nsubmitted {len(submitted)} / {len(m['orders'])}; refused/stopped {len(refused)}")
    log = MANIFEST_DIR / f"{m['run_id']}.execution.json"
    log.write_text(json.dumps({
        "manifest_sha256": stated,
        "classification": CLASSIFICATION,
        "operator_triggered": True,
        "submitted": [{"seq": o["seq"], "symbol": o["symbol"], "side": o["side"],
                       "qty": o["qty"], "order_id": oid} for o, oid in submitted],
        "refused": [{"seq": o["seq"], "symbol": o["symbol"], "reason": r} for o, r in refused],
        "completed_at_utc": datetime.now(UTC).isoformat(),
    }, indent=1, default=str))
    print(f"execution log: {log}")


def main() -> None:
    ap = argparse.ArgumentParser()
    sub = ap.add_subparsers(dest="cmd", required=True)
    p = sub.add_parser("plan")
    p.add_argument("--reason", default="one_time_operator_rebalance")
    p.add_argument("--session-date", default=None,
                   help="YYYY-MM-DD the plan is for; defaults to today (local/ET on the box).")
    p.add_argument("--label", default="PLAN_PENDING_REVIEW",
                   help="artifact_status stamped into the manifest, e.g. DRY_RUN_ONLY.")
    p.add_argument("--receipt", default=None,
                   help="Path to the same-day HOST factor-refresh receipt to EMBED in the "
                        "hashed body (REQUIRED for the governing manifest; rehearsals may omit).")
    p.add_argument("--no-require-fresh-cache", action="store_true",
                   help="Disable the per-symbol bar-cache freshness gate (needs a documented reason).")
    p.set_defaults(fn=cmd_plan)
    e = sub.add_parser("execute")
    e.add_argument("--manifest", required=True)
    e.add_argument("--approve-sha", required=True)
    e.add_argument("--pacing", default="1.0")
    e.add_argument("--dry-run", action="store_true")
    e.add_argument("--accept-drift", action="store_true")
    e.set_defaults(fn=cmd_execute)
    args = ap.parse_args()
    asyncio.run(args.fn(args))


if __name__ == "__main__":
    main()
