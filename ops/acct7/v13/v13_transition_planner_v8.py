async def cmd_plan(args) -> None:
    session_date = args.session_date or datetime.now().astimezone().date().isoformat()
    m = await build_plan(
        reason=args.reason,
        expected_session_date=session_date,
        require_fresh_cache=not args.no_require_fresh_cache,
        label=args.label,
        receipt_path=args.receipt,
    )
    MANIFEST_DIR.mkdir(parents=True, exist_ok=True)
    prefix = "DRY_RUN_ONLY__" if "DRY_RUN" in args.label else ""
    out = MANIFEST_DIR / f"{prefix}{m['run_id']}.json"
    out.write_text(json.dumps(m, indent=1, default=str))
    out.chmod(0o444)  # immutable-by-convention once written
    print_review(m)
    print(f"\nmanifest written: {out}")
    print(f"manifest_sha256:  {m['manifest_sha256']}")
    print("\nNOTHING WAS SUBMITTED. Execution requires explicit approval of this exact manifest.")


